import { ESLint } from 'eslint';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { compareReactDiagnostics, reactDiagnostic } from './react-hooks-baseline.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const eslint = new ESLint({ cwd: root, cache: true, cacheStrategy: 'content', cacheLocation: resolve(root, '.tmp/react-hooks-eslint-cache') });
const baseline = JSON.parse(readFileSync(resolve(root, 'scripts/react-hooks-baseline.json'), 'utf8'));
const results = await eslint.lintFiles(['apps/dashboard/**/*.{ts,tsx}']);
const actual = results.flatMap(result => {
  if (!result.messages.length) return [];
  result.source ??= readFileSync(result.filePath, 'utf8');
  return result.messages.map(message => reactDiagnostic(root, result, message));
});
const { regressions, existing, resolved } = compareReactDiagnostics(actual, baseline.diagnostics);
for (const row of regressions) console.error(`${row.file}:${row.line}:${row.column} ${row.rule}\n  ${row.description}`);
console.log(`React hooks: ${results.length} files, ${regressions.length} new diagnostics, ${existing} legacy diagnostics (${resolved} baseline diagnostics resolved).`);
if (existing) console.log('Legacy debt is explicit in scripts/react-hooks-baseline.json; no new exemptions are generated by this command.');
process.exitCode = regressions.length ? 1 : 0;
