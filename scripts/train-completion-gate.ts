/**
 * Offline trainer for the learned completion gate (R7).
 *
 * Reads the editor's pipeline_telemetry rows from the central DB, joins
 * request-side gate features (stage 'autocomplete', diag.gateF) with the
 * user's verdicts (autocomplete_accept / _partial / _reject, by
 * diag.requestId), fits a logistic regression, and REGENERATES
 * packages/shared/src/editor/completion-gate-weights.ts.
 *
 * Never runs at runtime. Guards: refuses to write below --min-samples
 * (default 200) labeled pairs; only rows whose diag.gateV matches the current
 * GATE_FEATURE_VERSION are used. Usage:
 *   pnpm tsx scripts/train-completion-gate.ts [--db <path>] [--dry-run]
 */
import { DatabaseSync } from 'node:sqlite';
import { writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { mcpDataDir } from '../packages/shared/src/utils/config.js';
import {
  GATE_FEATURE_VERSION,
  extractGateFeatures,
} from '../packages/shared/src/editor/completion-prefilter.js';
import { COMPLETION_GATE_WEIGHTS } from '../packages/shared/src/editor/completion-gate-weights.js';

const WEIGHTS_FILE = join(import.meta.dirname, '../packages/shared/src/editor/completion-gate-weights.ts');
const DIM = extractGateFeatures({ lineBefore: '', lineAfter: '', languageId: 'x', prefixTotalTrimmedLen: 0 }).length;

function arg(name: string): string | undefined {
  const at = process.argv.indexOf(name);
  return at >= 0 ? process.argv[at + 1] : undefined;
}

function collect(dbPath: string): { x: number[][]; y: number[] } {
  const db = new DatabaseSync(dbPath, { readOnly: true });
  try {
    // Feedback rows embed the request diag (recordFeedback spreads req.diag),
    // so each accept/partial/reject row carries its own gateF — feature source
    // and label arrive together; no separate request-row join needed.
    const features = new Map<string, number[]>();
    const labels = new Map<string, number>();
    const grab = (stage: string, label: number) => {
      for (const row of db.prepare(
        `SELECT diag FROM pipeline_telemetry WHERE pipeline_name = 'editor' AND stage = ? AND diag IS NOT NULL`,
      ).all(stage) as Array<{ diag: string }>) {
        try {
          const diag = JSON.parse(row.diag) as { requestId?: unknown; gateF?: unknown; gateV?: unknown };
          if (typeof diag.requestId !== 'string') continue;
          if (Array.isArray(diag.gateF) && diag.gateF.length === DIM && diag.gateV === GATE_FEATURE_VERSION) {
            features.set(diag.requestId, diag.gateF as number[]);
          }
          // accept/partial (1) wins over an earlier provisional reject (0).
          labels.set(diag.requestId, Math.max(labels.get(diag.requestId) ?? 0, label));
        } catch { /* skip */ }
      }
    };
    grab('autocomplete_reject', 0);
    grab('autocomplete_partial', 1);
    grab('autocomplete_accept', 1);
    const x: number[][] = [];
    const y: number[] = [];
    for (const [requestId, label] of labels) {
      const f = features.get(requestId);
      if (f) {
        x.push(f);
        y.push(label);
      }
    }
    return { x, y };
  } finally {
    db.close();
  }
}

/** Plain batch gradient descent with L2 — small data, no dependencies. */
function fit(x: number[][], y: number[]): { bias: number; weights: number[]; acc: number } {
  const n = x.length;
  const weights = new Array<number>(DIM).fill(0);
  let bias = 0;
  const lr = 0.3;
  const l2 = 1e-3;
  for (let epoch = 0; epoch < 400; epoch++) {
    let gb = 0;
    const gw = new Array<number>(DIM).fill(0);
    for (let i = 0; i < n; i++) {
      let z = bias;
      for (let j = 0; j < DIM; j++) z += weights[j]! * x[i]![j]!;
      const err = 1 / (1 + Math.exp(-z)) - y[i]!;
      gb += err;
      for (let j = 0; j < DIM; j++) gw[j]! += err * x[i]![j]!;
    }
    bias -= (lr * gb) / n;
    for (let j = 0; j < DIM; j++) weights[j] = weights[j]! - lr * (gw[j]! / n + l2 * weights[j]!);
  }
  let correct = 0;
  for (let i = 0; i < n; i++) {
    let z = bias;
    for (let j = 0; j < DIM; j++) z += weights[j]! * x[i]![j]!;
    if ((1 / (1 + Math.exp(-z)) >= 0.5 ? 1 : 0) === y[i]) correct++;
  }
  return { bias, weights, acc: n ? correct / n : 0 };
}

function emit(bias: number, weights: number[], samples: number): string {
  const t = COMPLETION_GATE_WEIGHTS.thresholds;
  const list = weights.map((w) => Math.round(w * 10_000) / 10_000).join(', ');
  return `/**
 * AUTO-GENERATED by \`pnpm tsx scripts/train-completion-gate.ts\` — do not
 * hand-edit values (regenerate instead). Logistic-regression weights for the
 * learned completion gate (R7 in completion-prefilter.ts), trained offline on
 * the editor's own shown→accept/reject telemetry (pipeline_telemetry rows).
 *
 * \`trainedAt: null\` is the NEUTRAL bootstrap: the gate is inert (rule R7
 * never fires, no features are extracted) until a training run writes real
 * weights — shipping behavior stays exactly the pre-gate behavior.
 *
 * Feature order is a versioned contract with \`extractGateFeatures\` — bump
 * \`version\` whenever the vector layout changes so stale telemetry rows are
 * excluded from training.
 */

export interface CompletionGateWeights {
  /** Feature-vector layout version (must match GATE_FEATURE_VERSION). */
  version: number;
  /** ISO timestamp of the training run; null = neutral bootstrap (gate off). */
  trainedAt: string | null;
  /** Labeled samples the weights were fitted on. */
  samples: number;
  bias: number;
  /** One weight per feature — see extractGateFeatures for the layout. */
  weights: readonly number[];
  /**
   * Skip when sigmoid(bias + w·f) < threshold[suppression]. Stricter modes
   * skip more (higher cut). Lenient mode never reaches R7 (deterministic
   * escape hatch) — its entry is kept for forward-compat.
   */
  thresholds: { strict: number; standard: number; lenient: number };
}

export const COMPLETION_GATE_WEIGHTS: CompletionGateWeights = {
  version: ${GATE_FEATURE_VERSION},
  trainedAt: '${new Date().toISOString()}',
  samples: ${samples},
  bias: ${Math.round(bias * 10_000) / 10_000},
  weights: [${list}],
  thresholds: { strict: ${t.strict}, standard: ${t.standard}, lenient: ${t.lenient} },
};
`;
}

const dbPath = arg('--db') ?? join(mcpDataDir(), 'index.db');
const minSamples = Number(arg('--min-samples') ?? 200);
if (!existsSync(dbPath)) {
  console.error(`telemetry DB not found: ${dbPath} (pass --db <path>)`);
  process.exit(1);
}
const { x, y } = collect(dbPath);
const positives = y.filter((v) => v === 1).length;
console.log(`labeled pairs: ${x.length} (accept/partial ${positives}, reject ${x.length - positives})`);
if (x.length < minSamples || positives === 0 || positives === x.length) {
  console.error(`refusing to train: need ≥${minSamples} pairs with both classes — keeping the current weights.`);
  process.exit(2);
}
const { bias, weights, acc } = fit(x, y);
console.log(`fit done: train accuracy ${(acc * 100).toFixed(1)}% · bias ${bias.toFixed(4)}`);
if (process.argv.includes('--dry-run')) {
  console.log(emit(bias, weights, x.length));
} else {
  writeFileSync(WEIGHTS_FILE, emit(bias, weights, x.length), 'utf-8');
  console.log(`wrote ${WEIGHTS_FILE}`);
}
