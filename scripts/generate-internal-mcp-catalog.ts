import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { allTools } from '../apps/mcp-server/tools/index.js';

// Build-time data only. Product preparation must not spawn a server just to
// discover this fixed first-party schema. Dynamic external MCP remains live.
const output = resolve(import.meta.dirname, '../packages/code-agent/src/tools/generated/internal-mcp-catalog.ts');
const tools = [...allTools].sort((left, right) => left.name.localeCompare(right.name))
  .map(({ name, description, inputSchema }) => ({ name, description, inputSchema }));
if (new Set(tools.map(tool => tool.name)).size !== tools.length) throw new Error('Duplicate built-in MCP tool');
const source = '// Generated by scripts/generate-internal-mcp-catalog.ts --write. Do not edit.\n'
  + 'export interface InternalMcpCatalogTool { name: string; description: string; inputSchema: Record<string, unknown> }\n'
  + `export const INTERNAL_MCP_CATALOG: readonly InternalMcpCatalogTool[] = ${JSON.stringify(tools, null, 2)};\n`;
if (process.argv.includes('--write')) {
  await mkdir(dirname(output), { recursive: true }); await writeFile(output, source);
} else {
  if ((await readFile(output, 'utf8')).replace(/\r\n/g, '\n') !== source) {
    throw new Error('Built-in MCP catalog is stale. Run node --import tsx scripts/generate-internal-mcp-catalog.ts --write');
  }
}
console.log(`Built-in MCP catalog ${process.argv.includes('--write') ? 'generated' : 'verified'}: ${tools.length} tools.`);
