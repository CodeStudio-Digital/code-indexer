/** Skeleton completo do workspace react (sem instrumentação — ver inject). */
export function buildReactWorkspaceFiles(input: DsTemplateInput): WorkspaceFile[] {
  return [
    { path: 'package.json', contents: rootPackageJson(input) },
    { path: '.gitignore', contents: rootGitignore() },
    { path: 'README.md', contents: rootReadme(input) },
    { path: 'pkg/package.json', contents: pkgPackageJson(input) },
    { path: 'pkg/src/tokens.css', contents: PKG_TOKENS_CSS },
    { path: 'pkg/src/index.ts', contents: PKG_INDEX_TS },
    { path: 'pkg/docs.md', contents: pkgDocsMd(input) },
    { path: 'app/package.json', contents: appPackageJson() },
    { path: 'app/tsconfig.json', contents: APP_TSCONFIG_JSON },
    { path: 'app/index.html', contents: appIndexHtml(input) },
    { path: 'app/src/main.tsx', contents: APP_MAIN_TSX },
    { path: 'app/src/App.tsx', contents: APP_APP_TSX },
    { path: 'app/src/gallery/registry.tsx', contents: APP_GALLERY_REGISTRY_TSX },
    { path: 'app/src/gallery/TokensPage.tsx', contents: APP_TOKENS_PAGE_TSX },
  ];
}

/** Deps da galeria react — instaladas via `npm install --workspace app`. */
