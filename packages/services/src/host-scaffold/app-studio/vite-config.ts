/**
 * vite.config.ts do template `cf-fullstack` — igual ao dos projetos
 * builder (stamp de seleção de elemento PRIMEIRO, depois react) + o
 * plugin oficial `@cloudflare/vite-plugin` (SPA + Worker em workerd na
 * mesma porta, bindings D1 emulados). O stamp só transforma .tsx/.jsx,
 * então o código do worker nunca é tocado por ele.
 */
import type { ViteStampContribution } from '../../sandbox/types.js';

export function renderAppViteConfig(stamp: ViteStampContribution, port: number): string {
  const aliasEntries = Object.entries(stamp.resolveAlias ?? {});
  const resolveLines =
    aliasEntries.length > 0
      ? [
          `  resolve: {`,
          `    alias: {`,
          ...aliasEntries.map(([k, v]) => `      ${JSON.stringify(k)}: ${v},`),
          `    },`,
          `  },`,
        ]
      : [];
  return [
    `// Generated by CodeStudio App Studio. Do not edit — element-selection`,
    `// stamp + Cloudflare dev runtime + pinned port live here.`,
    `import { defineConfig } from 'vite';`,
    `import { cloudflare } from '@cloudflare/vite-plugin';`,
    ...stamp.imports,
    ``,
    `export default defineConfig({`,
    `  plugins: [${[...stamp.pluginExprs, 'cloudflare()'].join(', ')}],`,
    ...resolveLines,
    `  server: {`,
    `    port: ${port},`,
    `    strictPort: true,`,
    `    host: true,`,
    `  },`,
    `});`,
    ``,
  ].join('\n');
}
