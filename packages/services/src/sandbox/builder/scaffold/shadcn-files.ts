/**
 * Static file contents pre-baked into a Builder React project to make it
 * Tailwind v4 + shadcn/ui ready WITHOUT running the interactive `npx shadcn
 * init` (which prompts and is flaky inside a locked-down container).
 *
 * Tailwind v4 is CSS-first: there is no `tailwind.config.cjs` — the theme,
 * dark variant and content sources all live in the CSS (`@import`,
 * `@theme`, `@custom-variant`, `@source`). The only remaining JS config is
 * the PostCSS plugin (`@tailwindcss/postcss`), kept as `.cjs` so it loads
 * as CommonJS regardless of the project's `"type": "module"`.
 *
 * The shadcn color tokens are kept as HSL *channels* in `:root` / `.dark`
 * (e.g. `--primary: 222.2 47.4% 11.2%`) and mapped to Tailwind color
 * utilities via `@theme inline { --color-primary: hsl(var(--primary)) }`,
 * so `bg-primary`, `text-muted-foreground`, `border-border`, etc. resolve.
 */

export const POSTCSS_CONFIG_CJS = String.raw`module.exports = { plugins: { '@tailwindcss/postcss': {} } };
`;

export const UTILS_TS = String.raw`import { type ClassValue, clsx } from 'clsx';
import { twMerge } from 'tailwind-merge';

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}
`;

