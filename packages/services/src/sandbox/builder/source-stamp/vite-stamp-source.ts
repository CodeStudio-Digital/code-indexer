/**
 * Source of the dev-only Vite plugin written into the project as
 * `.mcp/vite-mcp-stamp.mjs`. It runs the Babel stamp (`./babel-mcp-stamp.cjs`)
 * over `.tsx`/`.jsx` in an `enforce:'pre'` `transform` hook, so `data-mcp-loc`
 * lands in the rendered DOM regardless of how Vite ultimately transforms JSX.
 *
 * WHY a standalone plugin instead of `react({ babel: { plugins: [...] } })`:
 * `@vitejs/plugin-react` v6 (Vite 8 / Rolldown era) transforms JSX with **oxc**,
 * not Babel, and silently IGNORES its `babel` option — so the stamping Babel
 * plugin never ran and no element carried `data-mcp-loc` (element selection was
 * a dead no-op). Running the stamp ourselves as a pre-transform is
 * version-independent and coexists with plugin-react's Fast Refresh (which still
 * sees our stamped source downstream).
 *
 * `apply: 'serve'` keeps production `vite build` output clean (the stamp only
 * runs for the dev server), which is what the old `NODE_ENV === 'production'`
 * guard used to do.
 *
 * Written as a string because it is compiled into the project, not this package.
 * It loads `@babel/core` (a Builder dev-dependency) through a namespace import
 * that works on BOTH majors — v7 is CommonJS (Node synthesizes a `default`
 * export) and v8 is ESM-only with named exports and NO `default` — and the
 * sibling `.cjs` Babel plugin via Node's ESM↔CJS interop.
 */
export const VITE_STAMP_SOURCE = String.raw`// Generated by MCP Builder — dev-only element-selection source stamp. Do not edit.
// @babel/core is dual-major: v7 is CommonJS (Node synthesizes a default export
// = module.exports), v8 is ESM-only with named exports and NO default export.
// A bare default import throws on v8 ("does not provide an export named
// 'default'") and kills the vite.config load, so take the namespace and prefer
// its default (v7) or fall back to the namespace itself (v8) — either way
// babel.transformAsync resolves.
import * as babelCore from '@babel/core';
import mcpStamp from './babel-mcp-stamp.cjs';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const babel = babelCore.default ?? babelCore;

// .mcp/vite-mcp-stamp.mjs -> project root (parent of .mcp/), so data-mcp-loc is
// project-relative (e.g. "src/App.tsx:12:5"), never an absolute path.
const PROJECT_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const STAMP_RE = /\.[jt]sx$/;

export default function mcpStampVite() {
  return {
    name: 'mcp-stamp',
    enforce: 'pre',
    apply: 'serve',
    async transform(code, id) {
      const file = id.split('?')[0];
      if (!STAMP_RE.test(file) || file.includes('node_modules') || file.includes('/.mcp/')) {
        return null;
      }
      const res = await babel.transformAsync(code, {
        filename: file,
        cwd: PROJECT_ROOT,
        root: PROJECT_ROOT,
        babelrc: false,
        configFile: false,
        parserOpts: { plugins: ['jsx', 'typescript'] },
        plugins: [mcpStamp],
        sourceMaps: true,
      });
      if (!res || res.code == null) return null;
      return { code: res.code, map: res.map };
    },
  };
}
`;
