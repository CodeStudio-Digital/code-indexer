/**
 * Source of the Babel plugin written into the project as
 * `.mcp/babel-mcp-stamp.cjs` and wired into `@vitejs/plugin-react`'s
 * `babel.plugins`. It stamps every JSX opening element with:
 *   - `data-mcp-loc="<relpath>:<line>:<col>"` (the edit target)
 *   - `data-mcp-name="<EnclosingComponent>"` (display label)
 *
 * Written as a string (not a real module) because it must live inside the
 * sandbox container's filesystem, not this package's build output. It is
 * CommonJS so Babel can `require` it regardless of the project's module
 * type, and it runs in Node during dev transforms (so `require('node:path')`
 * is available).
 *
 * Production builds are skipped (`NODE_ENV === 'production'`) so shipped
 * output is never polluted with selection attributes.
 */
export const BABEL_STAMP_SOURCE = String.raw`// Generated by MCP Builder — do not edit. Stamps JSX with data-mcp-loc.
const path = require('node:path');

module.exports = function mcpStamp({ types: t }) {
  function enclosingName(p) {
    let cur = p.parentPath;
    while (cur) {
      const n = cur.node;
      if (n.type === 'FunctionDeclaration' && n.id) return n.id.name;
      if (n.type === 'ClassDeclaration' && n.id) return n.id.name;
      if (
        (n.type === 'VariableDeclarator' || n.type === 'FunctionExpression' || n.type === 'ArrowFunctionExpression') &&
        cur.parentPath &&
        cur.parentPath.node.type === 'VariableDeclarator' &&
        cur.parentPath.node.id &&
        cur.parentPath.node.id.name
      ) {
        return cur.parentPath.node.id.name;
      }
      if (n.type === 'VariableDeclarator' && n.id && n.id.name) return n.id.name;
      cur = cur.parentPath;
    }
    return null;
  }

  return {
    name: 'mcp-stamp',
    visitor: {
      JSXOpeningElement(p, state) {
        if (process.env.NODE_ENV === 'production') return;
        const node = p.node;
        const loc = node.loc;
        if (!loc) return;
        // Skip Fragments (<>...</>) and already-stamped nodes.
        const already = node.attributes.some(
          (a) => a.type === 'JSXAttribute' && a.name && a.name.name === 'data-mcp-loc',
        );
        if (already) return;
        const filename = (state.file && state.file.opts && state.file.opts.filename) || '';
        const root = (state.cwd || process.cwd());
        let rel = filename ? path.relative(root, filename).replace(/\\/g, '/') : '';
        const value = rel + ':' + loc.start.line + ':' + (loc.start.column + 1);
        node.attributes.push(
          t.jsxAttribute(t.jsxIdentifier('data-mcp-loc'), t.stringLiteral(value)),
        );
        const comp = enclosingName(p);
        if (comp) {
          node.attributes.push(
            t.jsxAttribute(t.jsxIdentifier('data-mcp-name'), t.stringLiteral(comp)),
          );
        }
      },
    },
  };
};
`;
