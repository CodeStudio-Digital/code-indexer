import type { ExportMeta } from '../atlas-types.js';

interface TexturePackerAtlas {
  frames: Record<string, {
    frame: { x: number; y: number; w: number; h: number };
    pivot?: { x: number; y: number };
  }>;
  meta: { size: { w: number; h: number } };
}

/** Array-shaped JSON so Unity's JsonUtility can consume it without packages. */
export function unityManifestText(atlasJson: string, meta: ExportMeta, image: string): string {
  const atlas = JSON.parse(atlasJson) as TexturePackerAtlas;
  return `${JSON.stringify({
    format: 'codestudio-unity-sprite-v1', image,
    sheetWidth: atlas.meta.size.w, sheetHeight: atlas.meta.size.h,
    frames: Object.entries(atlas.frames).map(([name, value]) => ({
      name, ...value.frame, pivotX: value.pivot?.x ?? meta.pivot.x, pivotY: value.pivot?.y ?? meta.pivot.y,
    })),
    animations: Object.entries(meta.animations ?? {}).map(([name, value]) => ({
      name, frames: value.frames, fps: value.fps ?? meta.fps ?? 8,
      loopMode: value.loopMode ?? (value.loop === false ? 'once' : 'loop'),
      durationsMs: value.durationsMs ?? [], action: value.action ?? '', direction: value.direction ?? '',
    })),
  }, null, 2)}\n`;
}

/** Self-contained, idempotent Unity Editor importer: slices the sheet and
 * creates/updates AnimationClip assets whenever a .codesprite.json changes. */
export function unityImporterText(): string {
  return `// Generated by CodeStudio Sprite Studio. Safe to overwrite.\n` +
`#if UNITY_EDITOR\nusing System;\nusing System.Collections.Generic;\nusing System.IO;\nusing System.Linq;\nusing UnityEditor;\nusing UnityEngine;\n\n` +
`public sealed class CodeStudioSpritePostprocessor : AssetPostprocessor {\n` +
`  private static bool queued;\n` +
`  static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom) {\n` +
`    if (!imported.Any(p => p.EndsWith(".codesprite.json", StringComparison.OrdinalIgnoreCase))) return;\n` +
`    if (queued) return; queued = true;\n` +
`    EditorApplication.delayCall += () => { queued = false; CodeStudioSpriteImporter.ReimportAll(); };\n` +
`  }\n` +
`}\n\n` +
`public static class CodeStudioSpriteImporter {\n` +
`  [Serializable] private sealed class Manifest { public string format; public string image; public int sheetHeight; public Frame[] frames; public Anim[] animations; }\n` +
`  [Serializable] private sealed class Frame { public string name; public int x,y,w,h; public float pivotX=.5f,pivotY=1f; }\n` +
`  [Serializable] private sealed class Anim { public string name; public string[] frames; public float fps=8; public string loopMode="loop"; }\n` +
`  [MenuItem("Assets/CodeStudio/Reimport Sprite Manifests")] public static void ReimportAll() {\n` +
`    foreach (var guid in AssetDatabase.FindAssets("t:TextAsset")) { var p=AssetDatabase.GUIDToAssetPath(guid); if (p.EndsWith(".codesprite.json",StringComparison.OrdinalIgnoreCase)) Import(p); }\n` +
`  }\n` +
`  private static void Import(string manifestPath) {\n` +
`    var m=JsonUtility.FromJson<Manifest>(File.ReadAllText(manifestPath)); if(m==null||m.format!="codestudio-unity-sprite-v1") return;\n` +
`    var dir=(Path.GetDirectoryName(manifestPath)??"Assets").Replace('\\\\','/'); var texturePath=dir+"/"+m.image;\n` +
`    AssetDatabase.ImportAsset(texturePath,ImportAssetOptions.ForceUpdate); var ti=AssetImporter.GetAtPath(texturePath) as TextureImporter; if(ti==null)return;\n` +
`    ti.textureType=TextureImporterType.Sprite; ti.spriteImportMode=SpriteImportMode.Multiple; ti.filterMode=FilterMode.Point; ti.mipmapEnabled=false; ti.alphaIsTransparency=true;\n` +
`    ti.spritesheet=m.frames.Select(f=>new SpriteMetaData{name=f.name,alignment=(int)SpriteAlignment.Custom,pivot=new Vector2(f.pivotX,1f-f.pivotY),rect=new Rect(f.x,m.sheetHeight-f.y-f.h,f.w,f.h)}).ToArray();\n` +
`    ti.SaveAndReimport(); var sprites=AssetDatabase.LoadAllAssetsAtPath(texturePath).OfType<Sprite>().ToDictionary(s=>s.name);\n` +
`    foreach(var a in m.animations??Array.Empty<Anim>()){ var clipPath=dir+"/"+a.name+".anim"; var clip=AssetDatabase.LoadAssetAtPath<AnimationClip>(clipPath)??new AnimationClip(); clip.frameRate=Mathf.Max(1,a.fps);\n` +
`      var keys=new List<ObjectReferenceKeyframe>(); for(int i=0;i<a.frames.Length;i++)if(sprites.TryGetValue(a.frames[i],out var s))keys.Add(new ObjectReferenceKeyframe{time=i/clip.frameRate,value=s});\n` +
`      AnimationUtility.SetObjectReferenceCurve(clip,new EditorCurveBinding{path="",type=typeof(SpriteRenderer),propertyName="m_Sprite"},keys.ToArray());\n` +
`      var so=new SerializedObject(clip); var settings=so.FindProperty("m_AnimationClipSettings"); settings.FindPropertyRelative("m_LoopTime").boolValue=a.loopMode!="once"; so.ApplyModifiedPropertiesWithoutUndo();\n` +
`      if(!AssetDatabase.Contains(clip))AssetDatabase.CreateAsset(clip,clipPath); else EditorUtility.SetDirty(clip); } AssetDatabase.SaveAssets();\n` +
`  }\n` +
`}\n#endif\n`;
}
