import { describe, it, expect } from 'vitest';
import { buildDdl } from '../ddl/build.js';
import { buildDml } from '../sql/dml.js';
import { quoteRelation, placeholder } from '../sql/identifiers.js';

/**
 * Pure Oracle dialect tests — the SQL strings without a live server (the driver
 * itself still needs a real instance to validate end-to-end).
 */
describe('oracle identifiers', () => {
  it('double-quotes idents and binds :N', () => {
    expect(quoteRelation('oracle', 'HR', 'EMPLOYEES')).toBe('"HR"."EMPLOYEES"');
    expect(placeholder('oracle', 0)).toBe(':1');
    expect(placeholder('oracle', 2)).toBe(':3');
  });
});

describe('oracle DML', () => {
  it('UPDATE is PK-scoped with :N placeholders', () => {
    const built = buildDml('oracle', { op: 'update', schema: 'HR', table: 'EMP', pk: { ID: 1 }, values: { NAME: 'Ada' } });
    expect(built.sql).toContain('UPDATE "HR"."EMP" SET "NAME" = :1');
    expect(built.sql).toContain('WHERE "ID" = :2');
    expect(built.params).toEqual(['Ada', 1]);
  });
});

describe('oracle DDL', () => {
  it('CREATE renders GENERATED…IDENTITY for auto-increment + PK constraint', () => {
    const [sql] = buildDdl('oracle', 'create', {
      create: { schema: 'HR', table: 'EMP', columns: [
        { name: 'ID', type: 'NUMBER', primaryKey: true, autoIncrement: true, nullable: false },
        { name: 'NAME', type: 'VARCHAR2(255)' },
      ] },
    });
    expect(sql).toContain('CREATE TABLE "HR"."EMP"');
    expect(sql).toContain('"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(sql).toContain('PRIMARY KEY ("ID")');
  });

  it('ALTER add-column omits COLUMN; modify uses MODIFY; rename is standard', () => {
    const add = buildDdl('oracle', 'alter', { alter: { schema: 'HR', table: 'EMP', actions: [{ kind: 'addColumn', column: { name: 'AGE', type: 'NUMBER' } }] } });
    expect(add[0]).toBe('ALTER TABLE "HR"."EMP" ADD "AGE" NUMBER');
    const mod = buildDdl('oracle', 'alter', { alter: { schema: 'HR', table: 'EMP', actions: [{ kind: 'modifyColumn', name: 'AGE', column: { name: 'AGE', type: 'NUMBER(10)', nullable: false } }] } });
    expect(mod[0]).toBe('ALTER TABLE "HR"."EMP" MODIFY "AGE" NUMBER(10) NOT NULL');
    const rc = buildDdl('oracle', 'alter', { alter: { schema: 'HR', table: 'EMP', actions: [{ kind: 'renameColumn', from: 'AGE', to: 'YEARS' }] } });
    expect(rc[0]).toBe('ALTER TABLE "HR"."EMP" RENAME COLUMN "AGE" TO "YEARS"');
    const rt = buildDdl('oracle', 'alter', { alter: { schema: 'HR', table: 'EMP', actions: [{ kind: 'renameTable', to: 'STAFF' }] } });
    expect(rt[0]).toBe('ALTER TABLE "HR"."EMP" RENAME TO "STAFF"');
  });
});
