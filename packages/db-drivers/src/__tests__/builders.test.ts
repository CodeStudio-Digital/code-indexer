import { describe, it, expect } from 'vitest';
import { buildDml } from '../sql/dml.js';
import { buildDdl } from '../ddl/build.js';
import { quoteRelation, orderBySql } from '../sql/identifiers.js';
import { buildTablePreview } from '../sql/preview.js';

/**
 * Pure builder tests — no native module, so these are NOT ABI-gated and run
 * everywhere. They pin the dialect quoting, placeholder style, and the
 * parameterized/display split.
 */
describe('buildTablePreview', () => {
  it('pg: WHERE (parameterized) + ORDER BY + LIMIT/OFFSET with continuous $-numbering', () => {
    const { sql, params } = buildTablePreview('postgres', '"public"."t"', {
      limit: 100, offset: 200,
      orderBy: { column: 'created', dir: 'desc' },
      where: [{ column: 'name', op: 'like', value: '%ada%' }, { column: 'age', op: '>=', value: '18' }],
    });
    expect(sql).toBe('SELECT * FROM "public"."t" WHERE "name" LIKE $1 AND "age" >= $2 ORDER BY "created" DESC LIMIT $3 OFFSET $4');
    expect(params).toEqual(['%ada%', '18', 101, 200]);
  });

  it('mysql: ? placeholders, where params then limit/offset', () => {
    const { sql, params } = buildTablePreview('mysql', '`db`.`t`', {
      limit: 50, offset: 0, where: [{ column: 'id', op: '=', value: '7' }],
    });
    expect(sql).toBe('SELECT * FROM `db`.`t` WHERE `id` = ? LIMIT ? OFFSET ?');
    expect(params).toEqual(['7', 51, 0]);
  });

  it('mssql: OFFSET/FETCH, where then offset then fetch (@pN continuous)', () => {
    const { sql, params } = buildTablePreview('mssql', '[dbo].[t]', {
      limit: 25, offset: 50, where: [{ column: 'x', op: '=', value: 'a' }],
    });
    expect(sql).toBe('SELECT * FROM [dbo].[t] WHERE [x] = @p0 ORDER BY (SELECT NULL) OFFSET @p1 ROWS FETCH NEXT @p2 ROWS ONLY');
    expect(params).toEqual(['a', 50, 26]);
  });

  it('isnull/isnotnull bind no params; unknown op is dropped', () => {
    const { sql, params } = buildTablePreview('postgres', '"t"', {
      limit: 10, offset: 0,
      where: [{ column: 'a', op: 'isnull' }, { column: 'b', op: 'isnotnull' }, { column: 'c', op: 'bogus' as 'like' }],
    });
    expect(sql).toBe('SELECT * FROM "t" WHERE "a" IS NULL AND "b" IS NOT NULL LIMIT $1 OFFSET $2');
    expect(params).toEqual([11, 0]);
  });

  it('no filter/sort → plain paginated select', () => {
    const { sql, params } = buildTablePreview('sqlite', '"t"', { limit: 100, offset: 0 });
    expect(sql).toBe('SELECT * FROM "t" LIMIT ? OFFSET ?');
    expect(params).toEqual([101, 0]);
  });
});

describe('orderBySql', () => {
  it('quotes the column + closes the direction enum (no injection)', () => {
    expect(orderBySql('postgres', { column: 'name', dir: 'asc' })).toBe('"name" ASC');
    expect(orderBySql('mysql', { column: 'created_at', dir: 'desc' })).toBe('`created_at` DESC');
    expect(orderBySql('mssql', { column: 'id', dir: 'asc' })).toBe('[id] ASC');
    // A malicious column name is quoted, not interpolated; an odd dir falls back to ASC.
    expect(orderBySql('postgres', { column: 'x"; DROP TABLE t;--', dir: 'evil' as 'asc' })).toBe('"x""; DROP TABLE t;--" ASC');
    expect(orderBySql('postgres', undefined)).toBeNull();
  });
});
describe('DML builder', () => {
  it('postgres UPDATE is PK-scoped with $-placeholders', () => {
    const built = buildDml('postgres', {
      op: 'update',
      schema: 'public',
      table: 'users',
      pk: { id: 7 },
      values: { name: "O'Brien", active: true },
    });
    expect(built.sql).toBe('UPDATE "public"."users" SET "name" = $1, "active" = $2 WHERE "id" = $3');
    expect(built.params).toEqual(["O'Brien", true, 7]);
    // Display escapes the quote and inlines literals.
    expect(built.display).toContain(`"name" = 'O''Brien'`);
    expect(built.display).toContain('WHERE "id" = 7');
  });

  it('mysql INSERT uses backticks and ? placeholders', () => {
    const built = buildDml('mysql', { op: 'insert', table: 'posts', values: { title: 'hi', views: 3 } });
    expect(built.sql).toBe('INSERT INTO `posts` (`title`, `views`) VALUES (?, ?)');
    expect(built.params).toEqual(['hi', 3]);
  });

  it('sqlite DELETE refuses without a primary key', () => {
    expect(() => buildDml('sqlite', { op: 'delete', table: 't', pk: {} })).toThrow(/primary key/i);
  });

  it('sqlite DELETE targets the pk', () => {
    const built = buildDml('sqlite', { op: 'delete', table: 't', pk: { id: 1 } });
    expect(built.sql).toBe('DELETE FROM "t" WHERE "id" = ?');
    expect(built.params).toEqual([1]);
  });
});

describe('DDL builder', () => {
  it('postgres CREATE with identity PK', () => {
    const [sql] = buildDdl('postgres', 'create', {
      create: {
        table: 'users',
        columns: [
          { name: 'id', type: 'bigint', primaryKey: true, autoIncrement: true, nullable: false },
          { name: 'email', type: 'text', nullable: false },
        ],
      },
    });
    expect(sql).toContain('"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(sql).toContain('"email" text NOT NULL');
    expect(sql).toContain('PRIMARY KEY ("id")');
  });

  it('sqlite CREATE inlines INTEGER PRIMARY KEY AUTOINCREMENT', () => {
    const [sql] = buildDdl('sqlite', 'create', {
      create: { table: 't', columns: [{ name: 'id', type: 'INTEGER', primaryKey: true, autoIncrement: true }] },
    });
    expect(sql).toContain('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
    expect(sql).not.toContain('PRIMARY KEY ("id")'); // not also a table-level constraint
  });

  it('mysql CREATE uses AUTO_INCREMENT + UNSIGNED', () => {
    const [sql] = buildDdl('mysql', 'create', {
      create: {
        table: 't',
        columns: [{ name: 'id', type: 'INT', primaryKey: true, autoIncrement: true, unsigned: true, nullable: false }],
      },
    });
    expect(sql).toContain('`id` INT UNSIGNED NOT NULL AUTO_INCREMENT');
    expect(sql).toContain('PRIMARY KEY (`id`)');
  });

  it('postgres ALTER modify expands to TYPE + NOT NULL + DEFAULT statements', () => {
    const stmts = buildDdl('postgres', 'alter', {
      alter: {
        table: 'users',
        actions: [{ kind: 'modifyColumn', name: 'age', column: { name: 'age', type: 'integer', nullable: false, default: '0' } }],
      },
    });
    expect(stmts).toContain('ALTER TABLE "users" ALTER COLUMN "age" TYPE integer');
    expect(stmts).toContain('ALTER TABLE "users" ALTER COLUMN "age" SET NOT NULL');
    expect(stmts).toContain('ALTER TABLE "users" ALTER COLUMN "age" SET DEFAULT 0');
  });

  it('mysql ALTER add + drop + rename column', () => {
    const stmts = buildDdl('mysql', 'alter', {
      alter: {
        table: 't',
        actions: [
          { kind: 'addColumn', column: { name: 'c', type: 'VARCHAR(10)', nullable: true } },
          { kind: 'dropColumn', name: 'old' },
          { kind: 'renameColumn', from: 'a', to: 'b' },
        ],
      },
    });
    expect(stmts[0]).toBe('ALTER TABLE `t` ADD COLUMN `c` VARCHAR(10)');
    expect(stmts[1]).toBe('ALTER TABLE `t` DROP COLUMN `old`');
    expect(stmts[2]).toBe('ALTER TABLE `t` RENAME COLUMN `a` TO `b`');
  });

  it('ALTER rename table per engine', () => {
    expect(buildDdl('postgres', 'alter', { alter: { table: 'old', actions: [{ kind: 'renameTable', to: 'new' }] } })).toEqual([
      'ALTER TABLE "old" RENAME TO "new"',
    ]);
    expect(buildDdl('mysql', 'alter', { alter: { table: 'old', actions: [{ kind: 'renameTable', to: 'new' }] } })).toEqual([
      'ALTER TABLE `old` RENAME TO `new`',
    ]);
  });

  it('add/drop index per engine', () => {
    expect(
      buildDdl('postgres', 'alter', { alter: { schema: 'app', table: 'users', actions: [{ kind: 'addIndex', index: { name: 'ix_email', columns: ['email'], unique: true } }] } }),
    ).toEqual(['CREATE UNIQUE INDEX "ix_email" ON "app"."users" ("email")']);
    expect(buildDdl('postgres', 'alter', { alter: { schema: 'app', table: 'users', actions: [{ kind: 'dropIndex', name: 'ix_email' }] } })).toEqual([
      'DROP INDEX "app"."ix_email"',
    ]);
    expect(buildDdl('mysql', 'alter', { alter: { table: 'users', actions: [{ kind: 'dropIndex', name: 'ix_email' }] } })).toEqual([
      'DROP INDEX `ix_email` ON `users`',
    ]);
  });

  it('add/drop foreign key per engine; sqlite is a comment', () => {
    const [pgFk] = buildDdl('postgres', 'alter', {
      alter: { table: 'posts', actions: [{ kind: 'addForeignKey', fk: { name: 'fk_user', columns: ['user_id'], refTable: 'users', refColumns: ['id'], onDelete: 'CASCADE' } }] },
    });
    expect(pgFk).toBe('ALTER TABLE "posts" ADD CONSTRAINT "fk_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE');
    expect(buildDdl('mysql', 'alter', { alter: { table: 'posts', actions: [{ kind: 'dropForeignKey', name: 'fk_user' }] } })).toEqual([
      'ALTER TABLE `posts` DROP FOREIGN KEY `fk_user`',
    ]);
    expect(buildDdl('postgres', 'alter', { alter: { table: 'posts', actions: [{ kind: 'dropForeignKey', name: 'fk_user' }] } })).toEqual([
      'ALTER TABLE "posts" DROP CONSTRAINT "fk_user"',
    ]);
    const [sqliteFk] = buildDdl('sqlite', 'alter', { alter: { table: 'posts', actions: [{ kind: 'addForeignKey', fk: { name: 'fk', columns: ['a'], refTable: 't', refColumns: ['id'] } }] } });
    expect(sqliteFk).toMatch(/rebuild/i);
  });

  it('sqlite modify column emits an unsupported comment (rebuild required)', () => {
    const [stmt] = buildDdl('sqlite', 'alter', {
      alter: { table: 't', actions: [{ kind: 'modifyColumn', name: 'x', column: { name: 'x', type: 'TEXT' } }] },
    });
    expect(stmt).toMatch(/rebuild/i);
  });

  it('rejects an invalid referential action (no injection via ON DELETE)', () => {
    expect(() =>
      buildDdl('postgres', 'alter', { alter: { table: 't', actions: [{ kind: 'addForeignKey', fk: { name: 'f', columns: ['a'], refTable: 'u', refColumns: ['id'], onDelete: 'CASCADE; DROP TABLE x' } }] } }),
    ).toThrow(/referential action/i);
  });

  it('rejects a statement-breaking column type/default (no injection)', () => {
    expect(() => buildDdl('postgres', 'create', { create: { table: 't', columns: [{ name: 'c', type: 'int); DROP TABLE x; --' }] } })).toThrow(/unsafe/i);
    expect(() => buildDdl('mysql', 'alter', { alter: { table: 't', actions: [{ kind: 'addColumn', column: { name: 'c', type: 'INT', default: "1; DROP TABLE x" } }] } })).toThrow(/unsafe/i);
  });

  it('quoteRelation omits sqlite main schema', () => {
    expect(quoteRelation('sqlite', 'main', 'users')).toBe('"users"');
    expect(quoteRelation('postgres', 'app', 'users')).toBe('"app"."users"');
  });
});
