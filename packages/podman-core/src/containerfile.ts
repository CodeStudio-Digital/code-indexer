/**
 * Pure Containerfile/.dockerignore generation for "containerize this project".
 * No I/O: the caller (plugin tool) reads which files exist + package.json, hands
 * the facts here, and writes the returned strings. Every template encodes the
 * same security defaults the assistant preaches: multi-stage, pinned base,
 * non-root USER, minimal final image, a .dockerignore.
 */

export type ContainerStack = 'node' | 'python' | 'go' | 'static';

/** Observable facts about a project root — gathered by the caller via fs. */
export interface StackFacts {
  hasPackageJson: boolean;
  /** Parsed package.json `scripts`, when readable. */
  scripts?: Record<string, string>;
  hasRequirements: boolean;
  hasPyproject: boolean;
  hasGoMod: boolean;
  hasIndexHtml: boolean;
}

export interface StackChoice {
  stack: ContainerStack;
  /** Suggested container port to EXPOSE/publish. */
  port: number;
}

/**
 * Pick the most likely stack from file facts. Returns null when nothing
 * recognizable is present (caller should ask the user to pass an explicit
 * stack). Order matters: Go and Python signals win over a bare package.json
 * only when package.json is absent.
 */
export function chooseStack(f: StackFacts): StackChoice | null {
  if (f.hasGoMod) return { stack: 'go', port: 8080 };
  if (f.hasPackageJson) {
    const s = f.scripts ?? {};
    // A build script with no start script → likely a static frontend bundle.
    if (s.build && !s.start) return { stack: 'static', port: 8080 };
    return { stack: 'node', port: 3000 };
  }
  if (f.hasRequirements || f.hasPyproject) return { stack: 'python', port: 8000 };
  if (f.hasIndexHtml) return { stack: 'static', port: 8080 };
  return null;
}

const HEADER = '# syntax=docker/dockerfile:1\n# Generated by the Podman plugin — multi-stage, non-root, least-privilege.\n';

function nodeFile(port: number, hasBuild: boolean): string {
  return `${HEADER}
FROM node:20-alpine AS deps
WORKDIR /app
COPY package*.json ./
RUN npm ci

FROM node:20-alpine AS build
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
RUN ${hasBuild ? 'npm run build' : 'echo "no build step"'}

FROM node:20-alpine AS runtime
ENV NODE_ENV=production
WORKDIR /app
COPY --chown=node:node --from=build /app ./
USER node
EXPOSE ${port}
HEALTHCHECK --interval=30s --timeout=3s CMD wget -qO- http://127.0.0.1:${port}/ || exit 1
CMD ["npm", "start"]
`;
}

function pythonFile(port: number): string {
  return `${HEADER}
FROM python:3.12-slim AS base
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1
WORKDIR /app
COPY requirements.txt ./
RUN pip install --no-cache-dir -r requirements.txt
COPY . .
RUN useradd --create-home --shell /usr/sbin/nologin app && chown -R app:app /app
USER app
EXPOSE ${port}
CMD ["python", "main.py"]
`;
}

function goFile(port: number): string {
  return `${HEADER}
FROM golang:1.22-alpine AS build
WORKDIR /src
COPY go.* ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 go build -trimpath -o /out/app ./...

FROM gcr.io/distroless/static:nonroot
COPY --from=build /out/app /app
USER nonroot:nonroot
EXPOSE ${port}
ENTRYPOINT ["/app"]
`;
}

function staticFile(hasPackageJson: boolean): string {
  const buildStage = hasPackageJson
    ? `FROM node:20-alpine AS build
WORKDIR /app
COPY package*.json ./
RUN npm ci
COPY . .
RUN npm run build

`
    : '';
  const copyFrom = hasPackageJson ? '--from=build /app/dist' : '.';
  return `${HEADER}
${buildStage}FROM nginxinc/nginx-unprivileged:alpine
COPY ${copyFrom} /usr/share/nginx/html
EXPOSE 8080
`;
}

export interface RenderOpts {
  port?: number;
  /** Whether a `build` script exists (node/static). */
  hasBuild?: boolean;
  hasPackageJson?: boolean;
}

/** Render a best-practices Containerfile for the chosen stack. */
export function renderContainerfile(stack: ContainerStack, opts: RenderOpts = {}): string {
  switch (stack) {
    case 'node':
      return nodeFile(opts.port ?? 3000, opts.hasBuild ?? false);
    case 'python':
      return pythonFile(opts.port ?? 8000);
    case 'go':
      return goFile(opts.port ?? 8080);
    case 'static':
      return staticFile(opts.hasPackageJson ?? false);
  }
}

const COMMON_IGNORE = [
  '.git',
  '.gitignore',
  '.env',
  '.env.*',
  '*.log',
  '.DS_Store',
  'Dockerfile',
  'Containerfile',
  '.dockerignore',
];

/** Render a stack-appropriate .dockerignore. */
export function renderDockerignore(stack: ContainerStack): string {
  const extra: Record<ContainerStack, string[]> = {
    node: ['node_modules', 'dist', 'build', 'coverage', 'npm-debug.log*'],
    static: ['node_modules', 'dist', 'build'],
    python: ['__pycache__', '*.pyc', '.venv', 'venv', '.pytest_cache'],
    go: ['bin', 'out'],
  };
  return [...extra[stack], ...COMMON_IGNORE].join('\n') + '\n';
}
